import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.request import Request, urlopen

MANIFEST_URL = "https://niceliketryce.github.io/FireRed-Evolv3D/release.json"
GAME_NAME = "FireRed-Evolv3D.3dsx"
MAX_GAME = 192 * 1024 * 1024
CHUNK = 64 * 1024


def load_manifest(path: Path | None = None) -> dict:
    if path is not None:
        raw = path.read_bytes()
    else:
        request = Request(MANIFEST_URL, headers={"User-Agent": "FireRed-Evolv3D-Wireless/1"})
        with urlopen(request, timeout=25) as response:
            raw = response.read(1024 * 1024 + 1)
    if len(raw) > 1024 * 1024:
        raise ValueError("Release information is too large.")
    data = json.loads(raw)
    output = data.get("output", {})
    if (data.get("distribution_scope") != "public-patch-data"
            or type(output.get("size")) is not int
            or not 1024 * 1024 <= output["size"] <= MAX_GAME
            or not isinstance(output.get("sha256"), str)
            or len(output["sha256"]) != 64
            or any(c not in "0123456789abcdef" for c in output["sha256"])):
        raise ValueError("Invalid current release information.")
    return data


def lock_source(path: Path):
    """On Windows, allow other readers but prevent replacement during a send."""
    if os.name != "nt":
        return path.open("rb")
    import ctypes
    import msvcrt
    from ctypes import wintypes
    create = ctypes.windll.kernel32.CreateFileW
    create.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                       wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE]
    create.restype = wintypes.HANDLE
    handle = create(str(path), 0x80000000, 1, None, 3, 0x80, None)
    if handle == wintypes.HANDLE(-1).value:
        raise OSError(ctypes.get_last_error(), "Cannot open and protect the selected game.")
    return os.fdopen(msvcrt.open_osfhandle(handle, os.O_RDONLY | os.O_BINARY), "rb")


def validated_source(path: Path, manifest: dict):
    path = path.resolve(strict=True)
    if path.suffix.lower() != ".3dsx" or not path.is_file():
        raise ValueError("Select the .3dsx generated by the FireRed Evolv3D patcher.")
    source = lock_source(path)
    try:
        before = os.fstat(source.fileno())
        if before.st_size != manifest["output"]["size"]:
            raise ValueError("This file does not match the current game. Build the current version first.")
        header = source.read(32)
        if len(header) != 32 or header[:4] != b"3DSX":
            raise ValueError("This is not a Nintendo 3DS homebrew game.")
        header_size = struct.unpack_from("<H", header, 4)[0]
        if header_size < 32 or header_size > 4096:
            raise ValueError("Invalid 3DSX header.")
        source.seek(0)
        digest = hashlib.sha256()
        while block := source.read(CHUNK):
            digest.update(block)
        after = os.fstat(source.fileno())
        if ((before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns)
                or digest.hexdigest() != manifest["output"]["sha256"]):
            raise ValueError("Game verification failed. Build a fresh copy with the official patcher.")
        source.seek(0)
        return source, after
    except BaseException:
        source.close()
        raise


def lan_address() -> str:
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        # Route selection only; UDP connect does not transmit a packet.
        probe.connect(("8.8.8.8", 80))
        address = probe.getsockname()[0]
    finally:
        probe.close()
    parsed = ipaddress.ip_address(address)
    if not parsed.is_private or parsed.is_loopback or parsed.is_link_local:
        raise ValueError("Connect this computer to your home Wi-Fi network first.")
    return address


class GameServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = False

    def __init__(self, address: str, port: int, source, stat, manifest: dict, minutes=30):
        parsed = ipaddress.ip_address(address)
        if parsed.version != 4 or not (parsed.is_private or parsed.is_loopback):
            raise ValueError("Wireless setup serves only on a private local IPv4 address.")
        self.source = source
        self.source_stat = stat
        self.manifest = manifest
        self.token = secrets.token_urlsafe(24)
        self.deadline = time.monotonic() + min(60, max(1, minutes)) * 60
        self.lock = threading.Lock()
        self.io_lock = threading.Lock()
        self.connections = threading.BoundedSemaphore(3)
        self.ranges: list[tuple[int, int]] = []
        self.bytes_sent = 0
        self.finished = False
        super().__init__((address, port), GameRequest)

    @property
    def url(self) -> str:
        return f"http://{self.server_address[0]}:{self.server_address[1]}/{self.token}/{GAME_NAME}"

    def mark_sent(self, start: int, end: int):
        with self.lock:
            merged = []
            for a, b in sorted(self.ranges + [(start, end)]):
                if merged and a <= merged[-1][1]:
                    merged[-1] = (merged[-1][0], max(merged[-1][1], b))
                else:
                    merged.append((a, b))
            self.ranges = merged
            self.bytes_sent = sum(b - a for a, b in merged)
            self.finished = merged == [(0, self.source_stat.st_size)]


class GameRequest(BaseHTTPRequestHandler):
    server_version = "FireRedWireless/1"
    sys_version = ""
    protocol_version = "HTTP/1.1"

    def log_message(self, *_):
        pass  # Do not put the private installation token into HTTP logs.

    def do_HEAD(self):
        self.send_game(False)

    def do_GET(self):
        self.send_game(True)

    def send_game(self, body: bool):
        server: GameServer = self.server
        self.connection.settimeout(20)
        wanted = f"/{server.token}/{GAME_NAME}"
        if not secrets.compare_digest(self.path.encode(), wanted.encode()):
            self.send_error(404)
            return
        if time.monotonic() >= server.deadline:
            self.send_error(410, "This installation session has expired.")
            return
        if not server.connections.acquire(blocking=False):
            self.send_error(503, "An installation is already in progress.")
            return
        try:
            size = server.source_stat.st_size
            current = os.fstat(server.source.fileno())
            if (current.st_size, current.st_mtime_ns) != (size, server.source_stat.st_mtime_ns):
                self.send_error(409, "The selected game changed. Start a new session.")
                return
            start, end = 0, size - 1
            requested = self.headers.get("Range")
            if requested:
                import re
                match = re.fullmatch(r"bytes=(\d+)-(\d*)", requested)
                if match:
                    start = int(match[1])
                    end = int(match[2]) if match[2] else size - 1
                if not match or not 0 <= start <= end < size:
                    self.send_response(416)
                    self.send_header("Content-Range", f"bytes */{size}")
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
            self.send_response(206 if requested else 200)
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Disposition", f'attachment; filename="{GAME_NAME}"')
            self.send_header("Content-Length", str(end - start + 1))
            self.send_header("Accept-Ranges", "bytes")
            self.send_header("Cache-Control", "no-store")
            if requested:
                self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self.end_headers()
            if body:
                # Keep one shared, protected source descriptor. The bounded
                # lock avoids interleaved seeks when FBI resumes a request.
                with server.io_lock:
                    server.source.seek(start)
                    left = end - start + 1
                    sent = start
                    while left:
                        block = server.source.read(min(CHUNK, left))
                        if not block:
                            raise OSError("Selected game ended early.")
                        self.wfile.write(block)
                        left -= len(block)
                        server.mark_sent(sent, sent + len(block))
                        sent += len(block)
                self.wfile.flush()
        except (OSError, ValueError):
            pass  # A cancelled request remains resumable; never claim completion.
        finally:
            server.connections.release()


def desktop(manifest_path=None, address=None, session=None, open_browser=True):
    from wireless_web import run_desktop
    run_desktop(manifest_path, address, session, open_browser)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, help="Explicit local release metadata for a local owner build")
    parser.add_argument("--file", type=Path, help="Serve without the desktop picker")
    parser.add_argument("--bind", help="Private LAN IPv4 address; auto-detected by default")
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--minutes", type=int, default=30)
    parser.add_argument("--session", type=Path, help="Write private local session details for a companion process")
    parser.add_argument("--no-open", action="store_true", help="Keep the local setup page in the background")
    args = parser.parse_args()
    if not args.file:
        desktop(args.manifest, args.bind, args.session, not args.no_open)
        return
    manifest = load_manifest(args.manifest)
    source, stat = validated_source(args.file, manifest)
    try:
        with GameServer(args.bind or lan_address(), args.port, source, stat, manifest, args.minutes) as server:
            if args.session:
                args.session.write_text(json.dumps({"url": server.url, "version": manifest["version"],
                                                   "size": stat.st_size, "sha256": manifest["output"]["sha256"]}), encoding="utf-8")
            print("Verified game ready for local wireless installation.", flush=True)
            server.serve_forever()
    finally:
        source.close()


if __name__ == "__main__":
    main()
