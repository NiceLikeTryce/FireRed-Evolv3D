class DesktopServer(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, manifest_path=None, address=None):
        self.token = secrets.token_urlsafe(24)
        self.manifest_path = manifest_path
        self.address = address
        self.game_server = None
        self.game_thread = None
        self.source = None
        self.temp = None
        self.preparing = threading.Lock()
        self.error = None
        self.stopped = False
        self.idle_deadline = time.monotonic() + 30 * 60
        super().__init__(("127.0.0.1", 0), DesktopRequest)

    @property
    def origin(self):
        return f"http://127.0.0.1:{self.server_address[1]}"

    @property
    def url(self):
        return self.origin + "/" + self.token + "/"

    def stop_game(self):
        if self.game_server:
            self.game_server.shutdown()
            self.game_server.server_close()
            self.game_server = None
        if self.game_thread:
            self.game_thread.join(timeout=2)
            self.game_thread = None
        if self.source:
            self.source.close()
            self.source = None
        if self.temp:
            self.temp.cleanup()
            self.temp = None
        self.stopped = True


class DesktopRequest(BaseHTTPRequestHandler):
    server_version = "FireRedWirelessDesktop/1"
    sys_version = ""

    def log_message(self, *_):
        pass

    def route(self):
        server: DesktopServer = self.server
        if self.headers.get("Host") != f"127.0.0.1:{server.server_address[1]}":
            return None
        path = self.path.split("?", 1)[0]
        prefix = "/" + server.token + "/"
        return path[len(prefix):] if path.startswith(prefix) else None

    def respond(self, data, content_type="application/json", code=200):
        if not isinstance(data, bytes):
            data = json.dumps(data).encode()
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Content-Security-Policy", "default-src 'none'; script-src 'self'; style-src 'unsafe-inline'; img-src 'self'; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        route = self.route()
        server: DesktopServer = self.server
        if route == "":
            self.respond(HTML, "text/html; charset=utf-8")
        elif route == "app.js":
            self.respond(JS, "text/javascript; charset=utf-8")
        elif route == "state":
            game = server.game_server
            ready = game is not None and time.monotonic() < game.deadline
            self.respond({"ready": ready, "stopped": server.stopped,
                          "error": server.error,
                          "version": game.manifest["version"] if game else None,
                          "percent": 100 * game.bytes_sent / game.source_stat.st_size if game else 0,
                          "finished": game.finished if game else False,
                          "session": game.token[:8] if game else None})
        elif route == "qr.png" and server.game_server:
            import qrcode
            image = qrcode.make(server.game_server.url,
                                error_correction=qrcode.constants.ERROR_CORRECT_M,
                                box_size=8, border=4)
            output = io.BytesIO()
            image.save(output, format="PNG")
            self.respond(output.getvalue(), "image/png")
        else:
            self.respond({"error": "Not found."}, code=404)

    def do_POST(self):
        from wireless_install import load_manifest, validated_source, lan_address, GameServer, MAX_GAME, CHUNK
        server: DesktopServer = self.server
        route = self.route()
        if (route not in {"game", "stop", "close"}
                or self.headers.get("Origin") != server.origin
                or self.headers.get("X-FRE-Upload") != "1"):
            self.respond({"error": "This request is not from the local setup page."}, code=403)
            return
        if not server.preparing.acquire(blocking=False):
            self.respond({"error": "Another game is being prepared."}, code=409)
            return
        try:
            server.error = None
            if route in {"stop", "close"}:
                server.stop_game()
                self.respond({"stopped": True})
                if route == "close":
                    threading.Thread(target=server.shutdown, daemon=True).start()
                return
            size = int(self.headers.get("Content-Length", "0"))
            if not 1024 * 1024 <= size <= MAX_GAME:
                raise ValueError("Choose the .3dsx generated by the patcher.")
            manifest = load_manifest(server.manifest_path)
            if size != manifest["output"]["size"]:
                raise ValueError("This game is not the current version. Build it again with the patcher.")
            server.stop_game()
            server.temp = tempfile.TemporaryDirectory(prefix="FireRed-Evolv3D-send-")
            path = Path(server.temp.name) / "FireRed-Evolv3D.3dsx"
            with path.open("wb") as file:
                left = size
                while left:
                    block = self.rfile.read(min(CHUNK, left))
                    if not block:
                        raise ValueError("The local file transfer stopped early.")
                    file.write(block)
                    left -= len(block)
            server.source, stat = validated_source(path, manifest)
            server.game_server = GameServer(server.address or lan_address(), 0, server.source, stat, manifest)
            server.game_thread = threading.Thread(target=server.game_server.serve_forever, daemon=True)
            server.game_thread.start()
            server.stopped = False
            server.idle_deadline = time.monotonic() + 30 * 60
            self.respond({"ready": True, "version": manifest["version"]})
        except Exception as error:
            server.stop_game()
            server.error = str(error)
            self.respond({"error": str(error)}, code=400)
        finally:
            server.preparing.release()


def run_desktop(manifest_path=None, address=None, session=None, open_browser=True):
    with DesktopServer(manifest_path, address) as server:
        finished = threading.Event()
        def expire():
            while not finished.wait(1):
                if time.monotonic() >= server.idle_deadline:
                    server.shutdown()
                    return
        threading.Thread(target=expire, daemon=True).start()
        if session:
            Path(session).write_text(json.dumps({"url": server.url}), encoding="utf-8")
        if open_browser:
            webbrowser.open(server.url)
        try:
            server.serve_forever()
        finally:
            finished.set()
            server.stop_game()
